#!/usr/bin/env python3
"""
Generate the 5 Orion theme packages. Each theme is a small directory with:
  - tokens.json   (the theme's color ramps — a subset of orion-framework's
                   tokens.json, just the theme key)
  - theme.json    (Orion desktop metadata: name, accent presets, font config)
  - README.md     (description + licensing)
  - gtk.css       (optional GTK3+ CSS extracted from the same tokens)
  - sddm.theme    (Orion SDDM theme definition)

The 5 themes are: orion-dark, orion-light, orion-midnight, orion-aurora,
orion-high-contrast. Colors come from desktop/orion-framework/data/tokens.json
so they stay in sync.
"""

import json
from pathlib import Path
from textwrap import dedent

REPO_ROOT = Path(__file__).resolve().parent.parent
THEMES_DIR = REPO_ROOT / "themes"
TOKENS_PATH = REPO_ROOT / "desktop" / "orion-framework" / "data" / "tokens.json"

THEME_DESCRIPTIONS = {
    "orion-dark": "Default theme — deep navy surfaces, blue accent. The classic Orion look.",
    "orion-light": "Daytime theme — bright surfaces, darker accent. For office use.",
    "orion-midnight": "OLED-friendly theme — pure black surfaces, violet accent. For OLED displays.",
    "orion-aurora": "Emerald accent on dark green. For variety.",
    "orion-high-contrast": "WCAG AAA compliant — pure black/white, no blur, no gradients, no shadows.",
}

ACCENT_PRESETS = ["blue", "cyan", "violet", "magenta", "amber", "emerald", "crimson"]


def hex_to_gtk(c: str) -> str:
    """Convert #RRGGBB or #AARRGGBB to GDK's rgb()/rgba() syntax."""
    if not c.startswith("#"):
        return c
    s = c.lstrip("#")
    if len(s) == 8:
        r = int(s[2:4], 16); g = int(s[4:6], 16); b = int(s[6:8], 16); a = int(s[0:2], 16) / 255
        return f"rgba({r},{g},{b},{a:.2f})"
    if len(s) == 6:
        r = int(s[0:2], 16); g = int(s[2:4], 16); b = int(s[4:6], 16)
        return f"rgb({r},{g},{b})"
    return c


def gtk_css(theme_name: str, tokens: dict) -> str:
    t = tokens["themes"][theme_name]
    surface = t["surface"]
    fg = t["foreground"]
    accent = t["accent"]
    border = t["border"]
    sem = t["semantic"]

    return dedent(f"""\
        /* Orion OS GTK3+ theme: {theme_name}
         * Generated by scripts/generate-themes.py from
         * desktop/orion-framework/data/tokens.json — do NOT edit by hand.
         */

        @define-color surface0 {hex_to_gtk(surface["0"])};
        @define-color surface1 {hex_to_gtk(surface["1"])};
        @define-color surface2 {hex_to_gtk(surface["2"])};
        @define-color surface3 {hex_to_gtk(surface["3"])};
        @define-color surface4 {hex_to_gtk(surface["4"])};

        @define-color fg_primary {hex_to_gtk(fg["primary"])};
        @define-color fg_secondary {hex_to_gtk(fg["secondary"])};
        @define-color fg_tertiary {hex_to_gtk(fg["tertiary"])};

        @define-color accent {hex_to_gtk(accent["500"])};
        @define-color accent_hover {hex_to_gtk(accent["700"])};

        @define-color border_default {hex_to_gtk(border["default"])};
        @define-color border_subtle {hex_to_gtk(border["subtle"])};

        @define-color success {hex_to_gtk(sem["success"])};
        @define-color warning {hex_to_gtk(sem["warning"])};
        @define-color danger {hex_to_gtk(sem["danger"])};
        @define-color info {hex_to_gtk(sem["info"])};

        /* Base widget styles. */
        * {{
            font-family: "Inter", "Noto Sans", sans-serif;
        }}

        window, dialog {{
            background-color: @surface0;
            color: @fg_primary;
        }}

        button {{
            background-color: @surface2;
            color: @fg_primary;
            border: 1px solid @border_default;
            border-radius: 8px;
            padding: 6px 12px;
        }}

        button:hover {{ background-color: @surface3; }}
        button:active {{ background-color: @surface4; }}
        button.suggested-action {{
            background-color: @accent;
            color: white;
            border-color: @accent;
        }}

        entry {{
            background-color: @surface1;
            color: @fg_primary;
            border: 1px solid @border_default;
            border-radius: 8px;
            padding: 6px 8px;
        }}

        entry:focus {{ border-color: @accent; }}

        list row {{
            padding: 8px 12px;
        }}
        list row:selected {{
            background-color: alpha(@accent, 0.2);
            color: @fg_primary;
        }}
        """)


def theme_json(theme_name: str, tokens: dict) -> str:
    t = tokens["themes"][theme_name]
    return json.dumps({
        "name": theme_name,
        "description": THEME_DESCRIPTIONS[theme_name],
        "accent_default": "blue" if theme_name != "orion-midnight" else "violet",
        "accent_presets": ACCENT_PRESETS,
        "surface": t["surface"],
        "foreground": t["foreground"],
        "accent": t["accent"],
        "semantic": t["semantic"],
        "border": t["border"],
        "font_family": tokens["typography"]["font_family"],
        "font_mono": tokens["typography"]["font_family_mono"],
    }, indent=2)


def readme(theme_name: str) -> str:
    return dedent(f"""\
        # {theme_name}

        {THEME_DESCRIPTIONS[theme_name]}

        Part of Orion OS. See `docs/design-system.md` at the repository root
        for the full design language.

        ## Files

        - `tokens.json` — color ramps for this theme (subset of
          `desktop/orion-framework/data/tokens.json`).
        - `theme.json` — Orion Desktop theme metadata.
        - `gtk.css` — GTK3+ CSS extracted from the same tokens. Drop into
          `~/.themes/{theme_name}/gtk-3.0/gtk.css` to apply.
        - `sddm.theme` — Orion SDDM theme definition.

        ## License

        CC-BY-SA-4.0 for the artwork; GPL-3.0-or-later for the JSON/CSS code.
        """)


def sddm_theme(theme_name: str, tokens: dict) -> str:
    t = tokens["themes"][theme_name]
    return dedent(f"""\
        # Orion SDDM theme definition for {theme_name}.
        # Loaded by /usr/share/sddm/themes/orion-{theme_name.split("-")[1]}/.

        [Theme]
        Name=Orion {theme_name.split("-")[1].title()}
        Description={THEME_DESCRIPTIONS[theme_name]}
        Author=Orion OS Project
        Type=qml
        Screenshot=preview.png
        MainScript=Main.qml
        ConfigFile=theme.conf
        ThemeDir=/usr/share/sddm/themes/orion-{theme_name.split("-")[1]}

        # Token values for the SDDM QML theme.
        [Colors]
        surface0={t["surface"]["0"]}
        surface1={t["surface"]["1"]}
        surface2={t["surface"]["2"]}
        accent={t["accent"]["500"]}
        fg_primary={t["foreground"]["primary"]}
        fg_secondary={t["foreground"]["secondary"]}
        """)


def main() -> int:
    tokens = json.loads(TOKENS_PATH.read_text())
    written = 0
    for theme_name in tokens["themes"].keys():
        if theme_name.startswith("_"):
            continue
        d = THEMES_DIR / theme_name
        d.mkdir(parents=True, exist_ok=True)
        (d / "tokens.json").write_text(json.dumps(
            {"themes": {theme_name: tokens["themes"][theme_name]}},
            indent=2))
        (d / "theme.json").write_text(theme_json(theme_name, tokens))
        (d / "gtk.css").write_text(gtk_css(theme_name, tokens))
        (d / "sddm.theme").write_text(sddm_theme(theme_name, tokens))
        (d / "README.md").write_text(readme(theme_name))
        written += 5
        print(f"  wrote {d}")
    print(f"\nGenerated {written} files across 5 themes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
